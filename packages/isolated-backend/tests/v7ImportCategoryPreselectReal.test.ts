import assert from "node:assert/strict";
import { after, before, describe, it } from "node:test";
import pg from "pg";
import { commandGrantForRole } from "@nzi/contracts";
import type { PlannedRow } from "../src/v7ClientImport";
import type { V7ImportRefreshSource } from "../src/v7ImportRefresh";
import { readV7ImportRows } from "../src/v7ImportRows";
import { createDisposableDatabase, TEST_DATABASE_URL, type DisposableDatabase } from "./support/database";

/**
 * BRIEF-v7-import-spanning-batch, the category pre-select (26 Nov): a factor filed under more than one category comes in filed where its
 * categories narrow to one — V7's own category, else the category its code's suffix names (the registry, 0110: `-u` upstream → 3.4,
 * `-d` downstream → 3.9), else the one that applies. Freight is the case: "Freighting goods" is claimed by 3.4 and by 3.9. A row whose
 * categories do not narrow carries no category, for a person to choose ("Choose a category to confirm").
 */
const ORG = "v7-preselect";
const JOB = "v7-job-pre";
const record = (over: Record<string, unknown>) => ({ qty: 0, uom: "km", factor: 0, ghg_unit: "kgCO2e", original_id: "x", reported_tco2e: 0, data_source: "Company Data", enabled: true, ...over });
const FREIGHT = { code: "9_402_3401_10_1", levels: ["Freighting goods", "HGV (all diesel)", "Average laden"], label: "Freight · HGV · diesel · average laden", rate: 0.11107 };
const row = (id: string, originalId: string, qty: number): PlannedRow => {
  const reported = Math.round(qty * FREIGHT.rate / 1000 * 1e6) / 1e6;
  return {
    scopeRowId: `v7-row-${id}`, legacyDbId: id, scope: "3", v7Scope: "3", sourceLabel: FREIGHT.label, reportLabel: FREIGHT.label,
    level1: FREIGHT.levels[0]!, level2: FREIGHT.levels[1]!, level3: FREIGHT.levels[2]!, level4: null, columnText: null, quantity: qty, unit: "km", datasetId: null, factorId: null,
    calculatedTco2e: reported, reviewStatus: "pending", enabled: true, applyPct: 100, dataConfidence: null, siteId: null, isAutoGenerated: false, autoPairKind: null, linkedRowId: null,
    migratedRecord: record({ qty, uom: "km", reported_tco2e: reported, original_id: originalId, factor: FREIGHT.rate, factor_db_id: "f-freight", enabled: true }) as unknown as PlannedRow["migratedRecord"],
    provenance: {}, lineage: [], counted: true,
  };
};
// Upstream (-u), downstream (-d), and the same factor with no suffix. V7's own category names none of them ("Freight" is no console category).
const ROWS = [row("40001", `${FREIGHT.code}-u`, 12_000), row("40002", `${FREIGHT.code}-d`, 8_000), row("40003", FREIGHT.code, 5_000)];
const v7Categories = { "40001": "Freight", "40002": "Freight", "40003": "Freight" };
const source: V7ImportRefreshSource = async () => ({ sourceSha256: "c".repeat(64), rows: ROWS, v7Categories });
const EMPTY_PLAN = { jobId: JOB, crosswalkVersion: "none", crosswalkSha256: "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", vintageDatasetIds: [], rows: [] };

describe("the category pre-select: a freight factor filed under 3.4 or 3.9 by its code's -u/-d suffix; with neither, a person chooses", { skip: TEST_DATABASE_URL ? false : "NZI_TEST_DATABASE_URL is not set" }, () => {
  let database: DisposableDatabase;
  let db: pg.Client;
  const rowsOf = async () => (await readV7ImportRows(database.pool, source, commandGrantForRole("consultant", ORG, "staff-consultant"), JOB, { basePlan: EMPTY_PLAN })).rows;

  before(async () => {
    database = (await createDisposableDatabase("v7preselect"))!;
    db = await database.admin();
    await db.query(`INSERT INTO nzi_console.organisations (organisation_id,name) VALUES ($1,$1)`, [ORG]);
    await db.query(`SELECT nzi_console.provision_organisation($1)`, [ORG]);
    await db.query(`SELECT set_config('app.organisation_id', $1, false)`, [ORG]);
    await db.query(`INSERT INTO nzi_console.clients (organisation_id,client_id,name,status) VALUES ($1,'cp','Preselect Client','active')`, [ORG]);
    await db.query(`INSERT INTO nzi_console.memberships (organisation_id, user_id, role_id, status, display_name) VALUES ($1, 'staff-consultant', 'consultant', 'active', 'staff-consultant')`, [ORG]);
    await db.query(`INSERT INTO nzi_console.emission_factor_datasets (organisation_id,dataset_id,name,version,valid_from,valid_to,country_code,status,source_name,licence,source_system,source_family,legacy_dataset_id,content_sha256)
                    VALUES ($1,'uk-ghg-gb-2024','DESNZ GB 2024','1','2024-01-01','2024-12-31','GB','active','Test','Source: test.','nzi-pro-v7','uk-ghg','uk-ghg-gb-2024',repeat('a',64))`, [ORG]);
    await db.query(`INSERT INTO nzi_console.emission_factors (organisation_id,dataset_id,factor_id,label,activity_unit,kgco2e_per_unit,scopes,source_levels,source_system,legacy_db_id,legacy_original_id)
                    VALUES ($1,'uk-ghg-gb-2024',$2,$3,'km',$4,ARRAY['3'],$5::text[],'nzi-pro-v7','f-freight',$6)`, [ORG, `uk-ghg-${FREIGHT.code}`, FREIGHT.label, FREIGHT.rate, FREIGHT.levels, FREIGHT.code]);
    await db.query(`INSERT INTO nzi_console.jobs (organisation_id,job_id,client_id,sequence,job_family,title,status,workflow_stage,reporting_year,reporting_period_start,reporting_period_end,source_system,legacy_db_id,legacy_job_number)
      VALUES ($1,$2,'cp',909,'crp','CRP','open','Data entry',2024,'2024-01-01','2024-12-31','nzi-pro-v7','909','J000909')`, [ORG, JOB]);
    await db.query(`INSERT INTO nzi_console.job_emissions_config (organisation_id,job_id,reporting_from,reporting_to,country_code) VALUES ($1,$2,'2024-01-01','2024-12-31','GB')`, [ORG, JOB]);
    await db.query(`INSERT INTO nzi_console.job_dataset_selections (organisation_id,job_id,dataset_id,selection_source,reason,selected_by) VALUES ($1,$2,'uk-ghg-gb-2024','manual','the job''s datasets (test)','staff-consultant')`, [ORG, JOB]);
  });
  after(async () => { await db?.end(); await database?.end(); });

  it("freight is claimed by both 3.4 and 3.9: the row's levels alone name two", async () => {
    const seen = await rowsOf();
    assert.ok(seen.every((entry) => [...entry.categories].sort().join(",") === "3.4,3.9"), JSON.stringify(seen.map((entry) => entry.categories)));
    assert.ok(seen.every((entry) => entry.v7Category === null), "V7's own category (\"Freight\") names no console category");
  });

  it("-u files it under 3.4 and -d under 3.9, automatically: each comes in pre-accepted on its own factor", async () => {
    const seen = await rowsOf();
    const of = (id: string) => seen.find((entry) => entry.legacyDbId === id)!;
    assert.deepEqual([of("40001").codeCategory, of("40001").lane, of("40001").pick?.match.categoryCode, of("40001").pick?.match.verdict], ["3.4", "pre-accepted", "3.4", "reproduces"]);
    assert.deepEqual([of("40002").codeCategory, of("40002").lane, of("40002").pick?.match.categoryCode], ["3.9", "pre-accepted", "3.9"]);
  });

  it("with no suffix the categories do not narrow: the row carries its suggestion without a category, for a person to choose", async () => {
    const plain = (await rowsOf()).find((entry) => entry.legacyDbId === "40003")!;
    assert.deepEqual([plain.codeCategory, plain.lane, plain.pick?.match.categoryCode, plain.pick?.match.verdict, plain.pick?.invalid ?? null],
      [null, "suggested", null, "reproduces", null]);
  });
});
