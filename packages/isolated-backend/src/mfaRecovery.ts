import { createHash, randomInt, randomUUID } from "node:crypto";
import type { PoolLike, Queryable } from "./postgres";
import { withAuthTransaction } from "./postgres";
import { decryptTotpSecret, verifyTotp } from "./credentials";

/**
 * MFA recovery codes for staff and portal sign-in (email programme phase 4-2, R7; 0182).
 *
 * - **Issued at enrolment** — staff `/enrol` and the portal accept page — as a set of {@link RECOVERY_CODE_COUNT}, shown once
 *   and stored only as their sha256. Issuing again revokes the unused rest of the earlier set.
 * - **Accepted once each in place of an authenticator code** at the MFA step, inside the sign-in challenge's own attempt
 *   limit, so they are no easier to guess at than the six digits they stand in for (about 48 bits each, against 20).
 * - **Regenerated by the person**, signed in, by proving their authenticator — so a stolen session alone cannot mint codes.
 * - Every issue and use is audited by the account's id — never a code.
 */

export const RECOVERY_CODE_COUNT = 10;
/** At or below this many left, sign-in says so and points to the account page. */
export const LOW_RECOVERY_CODES = 3;
/** No 0/O, 1/I/L, U/V — unambiguous when read off paper. 29 symbols, ten of them: about 48 bits. */
const ALPHABET = "ABCDEFGHJKMNPQRSTWXYZ23456789";
const LENGTH = 10;

export type RecoveryPrincipal = "staff" | "portal";
type Account = { organisationId: string; principal: RecoveryPrincipal; subjectId: string };

/** Uppercase, spaces and dashes dropped — what a person might type for `ABCDE-FGHJK`. */
export const normaliseRecoveryCode = (input: string) => input.toUpperCase().replace(/[\s-]/g, "");
/** A recovery code rather than an authenticator code: never six digits, always ten of the alphabet. */
export const looksLikeRecoveryCode = (input: string) => new RegExp(`^[${ALPHABET}]{${LENGTH}}$`).test(normaliseRecoveryCode(input));
const hashOf = (code: string) => createHash("sha256").update(normaliseRecoveryCode(code)).digest("hex");
const generateCode = () => {
  const raw = Array.from({ length: LENGTH }, () => ALPHABET[randomInt(ALPHABET.length)]).join("");
  return `${raw.slice(0, 5)}-${raw.slice(5)}`;
};

const entityType = (principal: RecoveryPrincipal) => principal === "staff" ? "staff_credential" : "portal_credential";
const audit = (db: Queryable, account: Account, action: "mfa.recovery.generated" | "mfa.recovery.used", after: Record<string, unknown>) =>
  db.query(
    `INSERT INTO nzi_console.audit_events (organisation_id,audit_event_id,actor_id,principal_type,action,entity_type,entity_id,correlation_id,after_json)
     VALUES ($1,$2,$3,$4,$5,$6,$3,$2,$7::jsonb)`,
    [account.organisationId, `audit-${randomUUID()}`, account.subjectId, account.principal, action, entityType(account.principal), JSON.stringify(after)]);

/** A fresh set for the account, in the caller's authentication transaction; the earlier set's unused codes are revoked. */
export async function issueRecoveryCodes(db: Queryable, account: Account, now = new Date()): Promise<string[]> {
  const at = now.toISOString();
  const revoked = await db.query(
    `UPDATE nzi_console.mfa_recovery_codes SET revoked_at = $4
      WHERE organisation_id = $1 AND principal = $2 AND subject_id = $3 AND used_at IS NULL AND revoked_at IS NULL RETURNING code_id`,
    [account.organisationId, account.principal, account.subjectId, at]);
  const batchId = randomUUID();
  const codes = new Set<string>();
  while (codes.size < RECOVERY_CODE_COUNT) codes.add(generateCode());
  for (const code of codes) {
    await db.query(
      `INSERT INTO nzi_console.mfa_recovery_codes (organisation_id, code_id, principal, subject_id, batch_id, code_hash, created_at)
       VALUES ($1,$2,$3,$4,$5,$6,$7)`,
      [account.organisationId, randomUUID(), account.principal, account.subjectId, batchId, hashOf(code), at]);
  }
  await audit(db, account, "mfa.recovery.generated", { principal: account.principal, batchId, count: codes.size, revokedEarlier: revoked.rows.length });
  return [...codes];
}

/**
 * Spend one code, in the caller's authentication transaction (the sign-in challenge's). Returns how many are left, or null
 * when the code is not a live one for this account.
 */
export async function useRecoveryCode(db: Queryable, account: Account, code: string, now = new Date()): Promise<{ remaining: number } | null> {
  if (!looksLikeRecoveryCode(code)) return null;
  const used = await db.query(
    `UPDATE nzi_console.mfa_recovery_codes SET used_at = $5
      WHERE organisation_id = $1 AND principal = $2 AND subject_id = $3 AND code_hash = $4 AND used_at IS NULL AND revoked_at IS NULL
      RETURNING code_id`,
    [account.organisationId, account.principal, account.subjectId, hashOf(code), now.toISOString()]);
  if (used.rows.length !== 1) return null;
  const remaining = await liveCount(db, account);
  await audit(db, account, "mfa.recovery.used", { principal: account.principal, remaining });
  return { remaining };
}

const liveCount = async (db: Queryable, account: Account) => (await db.query<{ n: number }>(
  `SELECT count(*)::int AS n FROM nzi_console.mfa_recovery_codes
    WHERE organisation_id = $1 AND principal = $2 AND subject_id = $3 AND used_at IS NULL AND revoked_at IS NULL`,
  [account.organisationId, account.principal, account.subjectId])).rows[0]!.n;

/** How many unused codes the account holds — for its account page. */
export function countRecoveryCodes(pool: PoolLike, account: Account): Promise<number> {
  return withAuthTransaction(pool, "read", (db) => liveCount(db, account));
}

export class RecoveryCodeError extends Error {
  constructor(message = "That authenticator code is not correct.") { super(message); this.name = "RecoveryCodeError"; }
}

/**
 * A new set, asked for by the signed-in person and proved with a current authenticator code — not a recovery code: the
 * point is a set that works, and a session alone is not proof of who holds the authenticator.
 */
export async function regenerateRecoveryCodes(
  pool: PoolLike, account: Account, input: { code: string }, encryptionKey: string, now = new Date(),
): Promise<string[]> {
  return withAuthTransaction(pool, "write", async (db) => {
    const found = account.principal === "staff"
      ? await db.query<{ totp_ciphertext: string; totp_iv: string; totp_tag: string; enabled: boolean }>(
        `SELECT totp_ciphertext, totp_iv, totp_tag, enabled FROM nzi_console.staff_credentials WHERE organisation_id = $1 AND user_id = $2`, [account.organisationId, account.subjectId])
      : await db.query<{ totp_ciphertext: string; totp_iv: string; totp_tag: string; enabled: boolean }>(
        `SELECT totp_ciphertext, totp_iv, totp_tag, enabled FROM nzi_console.portal_credentials WHERE organisation_id = $1 AND portal_user_id = $2`, [account.organisationId, account.subjectId]);
    const credential = found.rows[0];
    if (!credential?.enabled) throw new RecoveryCodeError("This account has no working sign-in.");
    const secret = decryptTotpSecret({ ciphertext: credential.totp_ciphertext, iv: credential.totp_iv, tag: credential.totp_tag }, encryptionKey);
    if (!verifyTotp(input.code.trim(), secret, now.getTime())) throw new RecoveryCodeError();
    return issueRecoveryCodes(db, account, now);
  });
}
